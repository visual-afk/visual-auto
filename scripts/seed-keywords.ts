function regionCat(kw: string): string {
  if (kw.includes('추천')) return '추천';
  if (kw.includes('헤어살롱')) return '헤어살롱';
  if (kw.includes('역 ')) return '역세권';
  return '동네';
}

function buildRows(branch: string, d: BranchData): string[][] {
  const rows: string[][] = [];
  // 빈칸 3개 = 월간 검색량 / 경쟁강도 / 신규블로그추천 (npm run keywords가 채움)
  const push = (cls: string, cat: string, kw: string) => rows.push([branch, cls, cat, kw, '', '', '']);

  for (const kw of d.region) push('지역', regionCat(kw), kw);
  for (const [cat, kws] of Object.entries(d.signature || {})) for (const kw of kws) push('시그니처', cat, kw);
  for (const [cat, kws] of Object.entries(d.main)) for (const kw of kws) push('메인', cat, kw);
  for (const [cat, kws] of Object.entries(d.longtail || {})) for (const kw of kws) push('세부(롱테일)', cat, kw);
  for (const [cat, kws] of Object.entries(LONGTAIL2[branch] || {})) for (const kw of kws) push('세부(롱테일)', cat, kw);
  return rows;
}

